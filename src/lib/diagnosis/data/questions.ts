import type { Condition, Option, Question, QuestionType } from "../types";

const YES_NO: Option[] = [
  { id: "yes", label: "بله" },
  { id: "no", label: "خیر" },
];

const YES_NO_UNKNOWN: Option[] = [
  ...YES_NO,
  { id: "unknown", label: "نمی‌دانم" },
];

function q(input: {
  id: string;
  text: string;
  priority: number;
  diagnosticValue: number;
  type?: QuestionType;
  options?: Option[];
  hint?: string;
  optional?: boolean;
  categoryId?: string;
  problemIds?: string[];
  extra?: Condition[];
}): Question {
  const conditions: Condition[] = [];
  if (input.categoryId) {
    conditions.push({ field: "categoryId", op: "eq", value: input.categoryId });
  }
  if (input.problemIds) {
    conditions.push({ field: "problemId", op: "in", value: input.problemIds });
  }
  if (input.extra) conditions.push(...input.extra);

  return {
    id: input.id,
    text: input.text,
    hint: input.hint,
    priority: input.priority,
    diagnosticValue: input.diagnosticValue,
    type: input.type ?? "single",
    options: input.options,
    optional: input.optional,
    conditions: conditions.length ? conditions : undefined,
  };
}

