export function isTehranServiceSlug(slug: string): slug is TehranServiceSlug {
  return (TEHRAN_SERVICE_SLUGS as readonly string[]).includes(slug);
}

export function getTehranPage(slug: string): TehranPageContent | undefined {
  if (!isTehranServiceSlug(slug)) return undefined;
  return tehranPages[slug];
}

export function tehranPagePath(slug: TehranServiceSlug): string {
  return `${TEHRAN_PATH}/${slug}`;
}

export function tehranSitemapPaths(): string[] {
  return [TEHRAN_PATH, ...TEHRAN_SERVICE_SLUGS.map(tehranPagePath)];
}
